const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
  const fixture = await require('./helpers/threejs-preview').start(0);
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'chrome', headless: true });
  const out = path.resolve(process.env.QA_OUT || '.qa/profile-style'); fs.mkdirSync(out, { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const base = `http://127.0.0.1:${fixture.port}`;
  const trigger = name => page.locator(`[data-style-picker="${name}"] .wagon-picker-trigger`);
  const choose = async (name, option) => { await trigger(name).click(); await page.getByRole('option', { name: option, exact: true }).click(); };
  const color = selector => page.locator(selector).evaluate(node => getComputedStyle(node).backgroundColor);
  try {
    await page.goto(`${base}/profile?tab=customization`);
    await trigger('color').waitFor();
    assert.equal(await page.locator('#customizationForm select, #customizationForm canvas').count(), 0);
    assert.equal(await color('.profile-heading .profile-avatar'), 'rgb(212, 87, 72)');
    await trigger('color').click();
    assert.equal(await page.getByRole('option').count(), 20);
    assert.equal(await page.locator('dialog[open] [role="option"][aria-selected="true"]').textContent(), 'RojoPasajeros✓');
    await page.waitForFunction(() => [...document.querySelectorAll('dialog[open] img')].every(img => img.complete && img.naturalWidth === 240));
    assert.equal(await page.locator('dialog[open] .wagon-picker-list').evaluate(node => node.scrollHeight > node.clientHeight), true);
    await page.screenshot({ path: path.join(out, 'selector-desktop.png') });
    await page.keyboard.press('End');
    assert.match(await page.locator(':focus').textContent(), /Índigo/);
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('[name="color"]').inputValue(), '#6269c7');
    assert.equal(await trigger('color').evaluate(node => node === document.activeElement), true);
    await choose('color', 'Jade Vivienda');
    assert.equal(await color('.avatar-choice:has([value="person"]) .profile-avatar-badge'), 'rgb(113, 187, 160)');
    assert.equal(await color('.avatar-choice:last-child .profile-avatar-badge'), 'rgb(113, 187, 160)');
    // The heading remains confirmed until the user saves; closing the picker cancels navigation.
    assert.equal(await color('.profile-heading .profile-avatar'), 'rgb(212, 87, 72)');
    await trigger('color').press('ArrowDown');
    assert.match(await page.locator(':focus').textContent(), /Jade/);
    await page.keyboard.press('Home'); await page.keyboard.press('Escape');
    assert.equal(await page.locator('[name="color"]').inputValue(), '#71bba0');
    await trigger('secondaryColor').click();
    assert.equal(await page.getByRole('option').count(), 21);
    assert.equal(await page.getByRole('option', { name: 'Jade Vivienda', exact: true }).getAttribute('aria-disabled'), 'true');
    await page.getByRole('option', { name: 'Azul Cisterna', exact: true }).click();
    await page.locator('[name="avatar"][value="capybara"]').check();
    await page.getByRole('button', { name: 'Guardar preferencias' }).click();
    await page.getByText('Preferencias guardadas.').waitFor();
    assert.equal(await color('.profile-heading .profile-avatar'), 'rgb(113, 187, 160)');
    assert.equal(await page.locator('.profile-heading .profile-avatar img').count(), 1);
    await page.reload(); await trigger('color').waitFor();
    assert.equal(await page.locator('[name="color"]').inputValue(), '#71bba0');
    assert.equal(await page.locator('[name="secondaryColor"]').inputValue(), '#458ad4');
    assert.equal(await page.locator('[name="avatar"][value="capybara"]').isChecked(), true);
    await page.screenshot({ path: path.join(out, 'profile-desktop.png'), fullPage: true });

    await page.setViewportSize({ width: 390, height: 844 });
    await trigger('color').click();
    const box = await page.locator('dialog[open]').boundingBox();
    assert.ok(Math.abs(box.y + box.height - 844) < 2);
    assert.ok(box.x >= 0 && box.x + box.width <= 391);
    await page.screenshot({ path: path.join(out, 'selector-mobile.png') });
    await page.keyboard.press('Home'); await page.keyboard.press('v');
    assert.match(await page.locator(':focus').textContent(), /Verde/);
    await page.keyboard.press('Enter');
    await choose('secondaryColor', 'Sin preferencia');
    assert.equal(await page.locator('[name="secondaryColor"]').inputValue(), '');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(out, 'profile-mobile.png'), fullPage: true });
    // A failed account save must keep the confirmed header and persisted preference.
    await page.evaluate(() => { window.realStyleSave = account.updateProfile; account.updateProfile = async () => { throw Error('Fallo de guardado de prueba'); }; });
    await page.getByRole('button', { name: 'Guardar preferencias' }).click();
    await page.getByText('Fallo de guardado de prueba').waitFor();
    assert.equal(await color('.profile-heading .profile-avatar'), 'rgb(113, 187, 160)');
    assert.equal(await page.evaluate(() => localStorage.getItem('rr-color')), '#71bba0');
    await page.evaluate(() => { account.updateProfile = window.realStyleSave; });
    await page.getByRole('button', { name: 'Guardar preferencias' }).click();
    await page.getByText('Preferencias guardadas.').waitFor();
    assert.equal(await color('.profile-heading .profile-avatar'), 'rgb(75, 157, 118)');
    // Unsaved changes disappear when leaving this tab. Repeated mounts leave one pair of dialogs.
    await choose('color', 'Marfil Silos de cemento');
    await page.locator('.profile-nav [data-profile="account"]').click();
    await page.locator('.profile-nav [data-profile="customization"]').click();
    await trigger('color').waitFor();
    assert.equal(await page.locator('[name="color"]').inputValue(), '#4b9d76');
    assert.equal(await page.locator('.wagon-picker-dialog').count(), 2);
    await page.evaluate(() => localStorage.setItem('rr-language', 'en')); await page.reload();
    await page.getByRole('button', { name: 'First color Green Alfalfa' }).waitFor();
    await trigger('color').click();
    await page.getByRole('option', { name: 'Blue Tank wagon', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    mobile.on('pageerror', error => errors.push(error.message));
    await mobile.goto(`${base}/profile?tab=customization`);
    await mobile.locator('[data-style-picker="color"] .wagon-picker-trigger').tap();
    const cdp = await mobile.context().newCDPSession(mobile);
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 200, y: 760 }] });
    for (let y = 730; y >= 490; y -= 40) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 200, y }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await mobile.waitForFunction(() => document.querySelector('dialog[open] .wagon-picker-list').scrollTop > 100);
    await mobile.getByRole('option', { name: 'Amarillo Transporte de deportivos', exact: true }).tap();
    assert.equal(await mobile.locator('[name="color"]').inputValue(), '#b88929');
    assert.equal(await mobile.locator('.avatar-choice .profile-avatar-badge').first().evaluate(node => getComputedStyle(node).backgroundColor), 'rgb(242, 211, 61)');
    await mobile.locator('.avatar-options').scrollIntoViewIfNeeded();
    await mobile.locator('[name="avatar"][value="capybara"]').check();
    await mobile.screenshot({ path: path.join(out, 'avatars-mobile.png') });
    await mobile.getByRole('button', { name: 'Guardar preferencias' }).tap();
    await mobile.getByText('Preferencias guardadas.').waitFor();
    await mobile.setViewportSize({ width: 320, height: 640 });
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await mobile.locator('[data-style-picker="secondaryColor"] .wagon-picker-trigger').tap();
    await mobile.getByRole('option', { name: 'Azul Cisterna', exact: true }).tap();
    await mobile.close();
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ ok: true, checks: ['20 real thumbnails', 'scroll and keyboard', 'mobile sheet and touch swipe', '320px layout', 'distinct preferences', 'live avatar preview', 'save and reload', 'failed save preserves header', 'discard unsaved changes', 'English labels', 'no console errors'], screenshots: out }));
  } catch (error) {
    await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true });
    throw error;
  } finally {
    await browser.close(); await require('../backend/server').shutdown();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
