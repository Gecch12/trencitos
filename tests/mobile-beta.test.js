"use strict";
const test = require("node:test"), assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path"), os = require("node:os"), crypto = require("node:crypto");
const { startMobileServer } = require("../scripts/mobile-server");
const { mobileConfig, betaServer } = require("../scripts/mobile-config");
const { bundleMobile } = require("../scripts/mobile-bundle");
const { connect } = require("./helpers/ws-client");
const Engine = require("../backend/engine");
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "trencitos-native-"));
const token = crypto.randomBytes(32).toString("hex"), other = crypto.randomBytes(32).toString("hex");
const peers = [];
let app, port, base;
test.before(async () => { app = await startMobileServer({ port: 0, stateFile: path.join(dir, "rooms.json") }); port = app.server.address().port; base = `http://127.0.0.1:${port}`; });
test.after(async () => { peers.forEach(c => c.close()); await app.shutdown(); fs.rmSync(dir, { recursive: true, force: true }); });
const headers = (guest = token) => ({ Origin: "capacitor://localhost", "X-Trencitos-Guest": guest });
test("native HTTP boundary permits explicit account routes and rejects browser cookies and invalid methods", async () => {
  const preflight = await fetch(base + "/api/history", { method: "OPTIONS", headers: { Origin: "https://localhost", "Access-Control-Request-Method": "GET", "Access-Control-Request-Headers": "x-trencitos-guest,accept" } });
  assert.equal(preflight.status, 204); assert.equal(preflight.headers.get("access-control-allow-origin"), "https://localhost");
  assert.equal(preflight.headers.get("access-control-allow-credentials"), null);
  const account = await fetch(base + "/api/account", { headers: { ...headers(), Cookie: "trencitos_guest=" + other } });
  assert.deepEqual(await account.json(), { enabled: false, profile: null, mobile: true });
  assert.equal(account.headers.get("set-cookie"), null);
  assert.equal((await fetch(base + "/api/history", { headers: { Origin: "capacitor://localhost", Cookie: "trencitos_guest=" + token } })).status, 401);
  assert.equal((await fetch(base + "/api/account", { method: "POST", headers: headers() })).status, 401);
  assert.equal((await fetch(base + "/api/account/logout", { method: "POST", headers: headers() })).status, 503);
  const foreign = await fetch(base + "/api/history", { headers: { ...headers(), Origin: "https://attacker.example" } });
  assert.equal(foreign.headers.get("access-control-allow-origin"), null);
  assert.equal((await fetch(base + "/api/history", { method: "OPTIONS", headers: { Origin: "capacitor://localhost", "Access-Control-Request-Method": "POST" } })).status, 403);
});
test("native WebSocket and HTTP share a durable guest identity without leaking private history", async () => {
  const a = await connect(port, { origin: "capacitor://localhost", protocols: `trencitos.v1, guest.${token}`, cookie: `trencitos_guest=${other}` }); peers.push(a);
  const b = await connect(port); peers.push(b);
  a.send({ type: "create", name: "Native", visibility: "private" }); const lobby = await a.next("lobby");
  b.send({ type: "join", code: lobby.code, name: "Browser" }); await b.next("lobby"); await a.next("lobby", m => m.members.length === 2);
  a.send({ type: "start" }); await a.next("state"); await b.next("state");
  const room = app.rooms.get(lobby.code), id = room.matchId;
  assert.equal(room.members[0].guestId, crypto.createHash("sha256").update(token).digest("hex"));
  const list = await (await fetch(base + "/api/history", { headers: headers() })).json();
  assert.equal(list.matches[0].id, id);
  assert.deepEqual((await (await fetch(base + "/api/history", { headers: headers(other) })).json()).matches, []);
  assert.equal((await fetch(base + "/api/history/" + id, { headers: headers(other) })).status, 404);
  Engine.finish(room.game, true); a.send({ type: "reclaim" }); await a.next("state", m => m.game.phase === "finished");
  const replay = await (await fetch(base + "/api/history/" + id, { headers: headers() })).json();
  assert.equal(replay.match.status, "completed"); assert.equal(replay.full, true);
  assert.ok(!JSON.stringify(replay).includes(token)); assert.ok(!JSON.stringify(replay).includes(lobby.token));
  assert.equal((await fetch(base + "/api/history/" + id + "/audit", { headers: headers(other) })).status, 404);
});
test("distribution bundles public files, uses HTTPS and disables native debugging", () => {
  const config = mobileConfig("android", undefined, "beta");
  assert.equal(config.server.url, undefined); assert.equal(config.server.cleartext, false);
  assert.equal(config.android.webContentsDebuggingEnabled, false); assert.equal(config.ios.webContentsDebuggingEnabled, false);
  for (const url of ["http://example.com", "https://localhost", "https://example.com/path", "https://a:b@example.com"]) assert.throws(() => betaServer(url, false));
  const output = path.join(dir, "bundle"); bundleMobile({ server: "https://example.com", output });
  const html = fs.readFileSync(path.join(output, "index.html"), "utf8");
  assert.match(html, /Content-Security-Policy/); assert.match(html, /https:\/\/example.com wss:\/\/example.com/);
  assert.match(fs.readFileSync(path.join(output, "mobile-runtime.js"), "utf8"), /https:\/\/example.com/);
  assert.ok(fs.existsSync(path.join(output, "vendor/three.module.js")));
  for (const privateFile of ["backend", "server.js", ".env", ".private", "package.json"]) assert.equal(fs.existsSync(path.join(output, privateFile)), false);
  const manifest = JSON.parse(fs.readFileSync(path.join(output, "manifest.webmanifest"), "utf8"));
  for (const icon of manifest.icons) assert.ok(fs.readFileSync(path.join(output, icon.src)).subarray(1, 4).equals(Buffer.from("PNG")));
});
